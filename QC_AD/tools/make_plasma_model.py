"""Adapt the installed AD g_plasma.mdl into the held/physical VR Plasma Gun.
Usage: python QC_AD/tools/make_plasma_model.py GAME/ad
Preserves the source mesh topology, UVs and indexed skins; no AI artwork needed.
"""
from pathlib import Path
import importlib.util, struct, sys, math
ROOT=Path(__file__).resolve().parents[2]
spec=importlib.util.spec_from_file_location('mdl',ROOT/'Misc/quakevr/blender/addons/quakevr_models/mdl.py')
mdl=importlib.util.module_from_spec(spec);spec.loader.exec_module(mdl)
folder=Path(sys.argv[1]);data=None
for pak in sorted(folder.glob('*.pak')):
    b=pak.read_bytes();magic,start,size=struct.unpack_from('<4sii',b);assert magic==b'PACK'
    for pos in range(start,start+size,64):
        name,offset,length=struct.unpack_from('<56sii',b,pos)
        if name.split(b'\0')[0]==b'progs/g_plasma.mdl':data=b[offset:offset+length]
loose=folder/'progs/g_plasma.mdl'
if loose.exists():data=loose.read_bytes()
if data is None:raise SystemExit('Installed AD progs/g_plasma.mdl not found')
m=mdl.Model(data,'g_plasma.mdl');assert len(m.frames)==1 and m.frames[0][0]=='simple'
original_skins=list(m.skins);original_tris=list(m.tris)
# Pickup points down -X and floats 24 units above origin. Rotate 180 degrees
# about Z, uniformly size to a ~75 cm rifle and align its pistol grip with VR.
verts=m.pose_bytes()[0]
points=[(-m.place(v)[0]*.45+3.3,-m.place(v)[1]*.45-.02,m.place(v)[2]*.45-16.5) for v in verts]
low=[min(p[i] for p in points) for i in range(3)];high=[max(p[i] for p in points) for i in range(3)]
scale=[(high[i]-low[i])/255 for i in range(3)]
packed=bytearray()
for p,v in zip(points,verts):
    n=mdl.anorms()[v[3]];normal=mdl.nearest_normal((-n[0],-n[1],n[2]))
    packed+=bytes([max(0,min(255,round((p[i]-low[i])/scale[i]))) for i in range(3)]+[normal])
m.h[2:5]=scale;m.h[5:8]=low;m.h[8]=max(math.sqrt(sum(x*x for x in p)) for p in points)
m.h[9:12]=[0.,0.,0.];m.h[19]=0 # no pickup rotation/trails
hdr=bytes([0,0,0,0,255,255,255,0])+b'vr_idle\0'.ljust(16,b'\0')
m.frames=[['simple',hdr,bytes(packed)]];m.trailing=b''
out=ROOT/'QC_AD/runtime/progs/advr_plasma.mdl';out.write_bytes(m.to_bytes())
out.with_name(out.name+'_0_norm.png').unlink(missing_ok=True) # old fallback UVs do not match
check=mdl.Model(out.read_bytes());assert check.skins==original_skins and check.tris==original_tris
order=mdl.strip_order(m.tris);actual=[m.place(v) for v in m.pose_bytes()[0]]
settings=dict(Scale=1,OffsetX=0,OffsetY=0,OffsetZ=0,Pitch=-7,Yaw=0,Roll=0,ZeroBlend=0,TwoHZeroBlend=0)
# Anchor indices are strip-order indices, NOT the source vertex indices.
# Anchor extra offsets use default world units (modelScale / offsetScale = 7/6).
def anchor(key,offsetkeys,point):
    idx=min(range(len(order)),key=lambda i:sum((actual[order[i]][j]-point[j])**2 for j in range(3)))
    settings[key]=idx
    for j,k in enumerate(offsetkeys):settings[k]=(point[j]-actual[order[idx]][j])*7/6
    return idx
anchor('MuzzleAnchorVertex',['MuzzleOffsetX','MuzzleOffsetY','MuzzleOffsetZ'],[high[0]+.05,-.02,-.5])
anchor('WpnButtonAnchorVertex',['WpnButtonX','WpnButtonY','WpnButtonZ'],[3,-1.57,-.6])
anchor('WpnTextAnchorVertex',['WpnTextX','WpnTextY','WpnTextZ'],[3,-1.57,.1])
settings.update(WpnButtonMode=1,WpnButtonPitch=0,WpnButtonYaw=0,WpnButtonRoll=0,WpnTextMode=1,WpnTextPitch=0,WpnTextYaw=0,WpnTextRoll=0,WpnTextScale=.22)
# Support grip under the forward receiver; stock remains available for bracing.
settings.update(Hotspot1Type=1,Hotspot1X=9.5,Hotspot1Y=-.02,Hotspot1Z=-3.5,Hotspot1Pitch=0,Hotspot1Yaw=0,Hotspot1Roll=0,
                Hotspot2Type=3,Hotspot2X=low[0],Hotspot2Y=-.02,Hotspot2Z=-.9)
settings.update(Recoil=1,RecoilStrength=5.5,RecoilTime=.8)
inc=ROOT/'Quake/vr/vr_ad_plasma.inc'
inc.write_text('// Generated by QC_AD/tools/make_plasma_model.py from installed AD g_plasma.mdl.\n'+''.join(f'AD_PLASMA_SETTING({k}, {v:.6f}f)\n' for k,v in settings.items()))
print('Converted',len(verts),'vertices;',len(m.tris),'triangles; skin',m.skin_size,'bounds',low,high)
print('Calibrated muzzle strip vertex',settings['MuzzleAnchorVertex'])
