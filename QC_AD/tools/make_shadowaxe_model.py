"""Adapt the installed AD g_shadaxe.mdl into the held/physical VR Shadow Axe.
Usage: python QC_AD/tools/make_shadowaxe_model.py GAME/ad
Preserves the source mesh topology, UVs and indexed skins; no AI artwork needed.
"""
from pathlib import Path
import importlib.util, struct, sys, math
ROOT=Path(__file__).resolve().parents[2]
spec=importlib.util.spec_from_file_location('mdl',ROOT/'Misc/quakevr/blender/addons/quakevr_models/mdl.py')
mdl=importlib.util.module_from_spec(spec);spec.loader.exec_module(mdl)
folder=Path(sys.argv[1]);data=None
for pak in sorted(folder.glob('*.pak')):
    b=pak.read_bytes();magic,start,size=struct.unpack_from('<4sii',b);assert magic==b'PACK'
    for pos in range(start,start+size,64):
        name,offset,length=struct.unpack_from('<56sii',b,pos)
        if name.split(b'\0')[0]==b'progs/g_shadaxe.mdl':data=b[offset:offset+length]
loose=folder/'progs/g_shadaxe.mdl'
if loose.exists():data=loose.read_bytes()
if data is None:raise SystemExit('Installed AD progs/g_shadaxe.mdl not found')
m=mdl.Model(data,'g_shadaxe.mdl');assert len(m.frames)==1 and m.frames[0][0]=='simple'
m.skins=[m.skins[4]] # Native weapon_upgrade_axe selects skin 4.
original_skins=list(m.skins);original_tris=list(m.tris)
# Stand the diagonal pickup handle upright with the same slight lean as the VR axe.
verts=m.pose_bytes()[0];angle=math.radians(22);c=math.cos(angle);sn=math.sin(angle)
def rotate(p):return (c*p[0]-sn*p[2],p[1],sn*p[0]+c*p[2])
points=[]
for v in verts:
    x,y,z=m.place(v);q=rotate((x+15,y,z-21))
    points.append((q[0]*.4-.5,q[1]*.4-.3,q[2]*.4-2.6))
low=[min(p[i] for p in points) for i in range(3)];high=[max(p[i] for p in points) for i in range(3)]
scale=[(high[i]-low[i])/255 for i in range(3)]
packed=bytearray()
for p,v in zip(points,verts):
    normal=mdl.nearest_normal(rotate(mdl.anorms()[v[3]]))
    packed+=bytes([max(0,min(255,round((p[i]-low[i])/scale[i]))) for i in range(3)]+[normal])
m.h[2:5]=scale;m.h[5:8]=low;m.h[8]=max(math.sqrt(sum(x*x for x in p)) for p in points)
m.h[9:12]=[0.,0.,0.];m.h[19]=0 # no pickup rotation/trails
hdr=bytes([0,0,0,0,255,255,255,0])+b'vr_idle\0'.ljust(16,b'\0')
m.frames=[['simple',hdr,bytes(packed)]];m.trailing=b''
out=ROOT/'QC_AD/runtime/progs/advr_shadowaxe.mdl';out.write_bytes(m.to_bytes())
out.with_name(out.name+'_0_norm.png').unlink(missing_ok=True) # old fallback UVs do not match
check=mdl.Model(out.read_bytes());assert check.skins==original_skins and check.tris==original_tris
order=mdl.strip_order(m.tris);actual=[m.place(v) for v in m.pose_bytes()[0]]
settings=dict(Scale=1,OffsetX=0,OffsetY=0,OffsetZ=0,Pitch=0,Yaw=0,Roll=0,ZeroBlend=0,TwoHZeroBlend=0)
# Anchor indices are strip-order indices, NOT the source vertex indices.
# Anchor extra offsets use default world units (modelScale / offsetScale = 7/6).
def anchor(key,offsetkeys,point):
    idx=min(range(len(order)),key=lambda i:sum((actual[order[i]][j]-point[j])**2 for j in range(3)))
    settings[key]=idx
    for j,k in enumerate(offsetkeys):settings[k]=(point[j]-actual[order[idx]][j])*7/6
    return idx
# Leading cutting edge, rather than the floating pickup origin, drives melee/parries.
blade=max(points,key=lambda p:p[0])
anchor('MuzzleAnchorVertex',['MuzzleOffsetX','MuzzleOffsetY','MuzzleOffsetZ'],blade)
settings.update(WpnButtonMode=0,WpnTextMode=0,Hotspot1Type=0,Hotspot2Type=0)
inc=ROOT/'Quake/vr/vr_ad_shadowaxe.inc'
inc.write_text('// Generated by QC_AD/tools/make_shadowaxe_model.py from installed AD g_shadaxe.mdl, skin 4.\n'+''.join(f'AD_SHADOWAXE_SETTING({k}, {v:.6f}f)\n' for k,v in settings.items()))
print('Converted',len(verts),'vertices;',len(m.tris),'triangles; skin',m.skin_size,'bounds',low,high)
print('Blade contact',blade,'strip vertex',settings['MuzzleAnchorVertex'])
