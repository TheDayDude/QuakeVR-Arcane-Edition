 for _,a,b,c in m.tris:
  u=[points[b][i]-points[a][i] for i in range(3)];v=[points[c][i]-points[a][i] for i in range(3)]
  n=[u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0]]
  for j in [a,b,c]:normals[j]=[normals[j][i]-n[i] for i in range(3)]
 packed=bytearray()
 for p,n in zip(points,normals):
  d=max(.0001,math.sqrt(sum(x*x for x in n)));ni=mdl.nearest_normal([x/d for x in n])
  packed+=bytes([max(0,min(255,round((p[i]-lo[i])/scale[i]))) for i in range(3)]+[ni])
 m.h[2:5]=scale;m.h[5:8]=lo;m.h[8]=max(math.sqrt(sum(x*x for x in p)) for p in points);m.h[19]=0
 m.frames=[['simple',bytes([0,0,0,0,255,255,255,0])+b'vr_idle\0'.ljust(16,b'\0'),bytes(packed)]];m.trailing=b''

