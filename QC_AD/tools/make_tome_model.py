def asset(folder,name):
 data=None
 for pak in sorted(folder.glob('*.pak')):
  b=pak.read_bytes();_,start,size=struct.unpack_from('<4sii',b)
  for p in range(start,start+size,64):
   n,o,z=struct.unpack_from('<56sii',b,p)
   if n.split(b'\0')[0].decode()==name:data=b[o:o+z]
 loose=folder/name
 if loose.exists():data=loose.read_bytes()
 if data is None:raise ValueError(name)
 return data

def write_mesh(m,points):
 lo=[min(p[i] for p in points) for i in range(3)];hi=[max(p[i] for p in points) for i in range(3)]
