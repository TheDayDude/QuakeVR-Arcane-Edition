"""Separate AD corpse weapons from body rigs; regenerate after make_ragdolls.py.

Profiles are audited connected components of the shipped AD 1.80 meshes.
No skin, UV, triangle, or living-pose edits are made. Zombie knights gib on
real death and use the QC weapon-debris filter, not their living knockdown poses.
"""
from pathlib import Path
import argparse, importlib.util, json, re, struct
import numpy as np
ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('ragdoll_mdl', ROOT/'Misc/quakevr/ragdoll/mdl.py')
mdl = importlib.util.module_from_spec(spec); spec.loader.exec_module(mdl)

def generate(pakdir):
    assets = {}
    for pak in sorted(Path(pakdir).glob('pak*.pak')):
        data = pak.read_bytes(); _, off, size = struct.unpack_from('<4sii', data)
        for at in range(off, off + size, 64):
            name, pos, length = struct.unpack_from('<56sii', data, at)
            name = name.split(b'\0')[0].decode()
            if name.startswith('progs/mon_') and name.endswith('.mdl'):
                assets[name] = data[pos:pos+length]
    profiles = json.loads(Path(__file__).with_name('weapon-meshes.json').read_text())
    rigs_path = ROOT/'Quake/vr/vr_ad_rigs.inc'
    rigs = rigs_path.read_text()
    out = ['// Generated by QC_AD/tools/make_weapon_meshes.py; AD 1.80 only.',
           'struct ADWeaponMesh { const char* model; int verts, tris, poses; const int* vertices; int count; int firstDeath, lastDeath; };']
    entries = []
    for row in profiles:
        model = row['model']; key = Path(model).stem; prefix = 'ad_' + key
        names, poses, tris = mdl.load(assets[model]); nv = len(poses[0])
        assert (nv, len(tris), len(poses)) == (row['verts'], row['tris'], row['poses']), model
        weapon = set(row['weaponVertices']); deaths = row['deathFrames']
        assert deaths == list(range(min(deaths), max(deaths)+1))
        keys = {}; reps = [keys.setdefault(poses[:, v].tobytes(), v) for v in range(nv)]
        # Disconnected components only: do not tear hands or create stretched triangles.
        for tri in tris:
            if 0 < sum(int(v) in weapon for v in tri) < 3:
                assert len({reps[v] for v in tri}) < 3, (model, tri)
        modified = poses.copy()
        for f in deaths: modified[f, sorted(weapon)] = poses[f, min(weapon)]
        body = sorted(set(range(nv))-weapon)
        assert np.array_equal(modified[:, body], poses[:, body])
        living = sorted(set(range(len(poses)))-set(deaths))
        assert np.array_equal(modified[living], poses[living])
        # Regeneration is idempotent: strip our old loose seed before rebuilding.
        seedpat = rf'constexpr Seed {prefix}Seeds\[\] = \{{\n(.*?)\n\}};'
        match = re.search(seedpat, rigs, re.S)
        if match:
            lines = match[1].splitlines()
            labelpat = rf'constexpr uint8_t {prefix}Labels\[\] = \{{\n(.*?)\n\}};'
            labels = list(map(int, re.findall(r'\d+', re.search(labelpat, rigs, re.S)[1])))
            parents = [int(re.search(r'"[^\"]+", (-?\d+)', line)[1]) for line in lines]
            counts = [len({reps[v] for v in body if labels[v] == b}) for b in range(len(lines))]
            keep = [b for b, count in enumerate(counts) if count >= 3]
            assert 0 in keep, (model, counts)
            mapping = {b: i for i,b in enumerate(keep)}
            def ancestor(b):
                while b >= 0 and b not in mapping: b = parents[b]
                return mapping[b] if b >= 0 else -1
            newlines = []
            for b in keep:
                newlines.append(re.sub(r'("[^\"]+", )-?\d+', lambda m: m[1]+str(ancestor(parents[b])), lines[b], count=1))
            for v in body:
                b = ancestor(labels[v]); assert b >= 0
                labels[v] = b
            for v in weapon: labels[v] = len(keep)
            p = poses[0, sorted(weapon)].mean(axis=0)
            xyz = '{' + ', '.join(f'{x:.4f}f' for x in p) + '}'
            newlines.append('    {"loose_weapon", -1, Joint::Loose, '+', '.join([xyz]*3)+', 0.f, 0.f, 0.f, 0.f, {}},')
            rigs = re.sub(seedpat, lambda m: f'constexpr Seed {prefix}Seeds[] = {{\n'+ '\n'.join(newlines)+'\n};', rigs, flags=re.S)
            labtext = '\n'.join('    '+','.join(map(str,labels[i:i+48]))+',' for i in range(0,nv,48))
            rigs = re.sub(labelpat, lambda m: f'constexpr uint8_t {prefix}Labels[] = {{\n'+labtext+'\n};', rigs, flags=re.S)
            rigs = re.sub(rf'({prefix}Seeds, )\d+', lambda m:m[1]+str(len(newlines)), rigs)
            print(model, 'body bones',len(keep),'weapon vertices',len(weapon))
        out.append(f'constexpr int {prefix}Weapon[] = {{'+','.join(map(str, sorted(weapon)))+'};')
        entries.append(f'    {{"{model}", {nv}, {len(tris)}, {len(poses)}, {prefix}Weapon, {len(weapon)}, {min(deaths)}, {max(deaths)}}},')
    out += ['constexpr ADWeaponMesh adWeaponMeshes[] = {'] + entries + ['};', '']
    (ROOT/'Quake/vr/vr_ad_weapon_meshes.inc').write_text('\n'.join(out))
    rigs_path.write_text(rigs)

if __name__ == '__main__':
    ap=argparse.ArgumentParser(); ap.add_argument('pakdir',type=Path)
    generate(ap.parse_args().pakdir)
